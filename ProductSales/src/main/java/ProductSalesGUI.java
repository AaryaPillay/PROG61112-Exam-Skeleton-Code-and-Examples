private void loadProductData() {

    int[][] data = sales.GetProductSales();

    StringBuilder output = new StringBuilder();

    output.append("DATA LOG\n");
    output.append("============================\n\n");

    output.append("Microphone\tSpeakers\tMixing Desk\n");

    for (int i = 0; i < data.length; i++) {

        output.append("Year " + (i + 1) + ":\t");

        for (int j = 0; j < data[i].length; j++) {

            output.append(data[i][j] + "\t");
        }

        output.append("\n");
    }

    output.append("\n");

    output.append("Total Sales: ")
          .append(sales.GetTotalSales()).append("\n");

    output.append("Average Sales: ")
          .append(Math.round(sales.GetAverageSales()))
          .append("\n");

    output.append("Sales over limit: ")
          .append(sales.GetSalesOverLimit()).append("\n");

    output.append("Sales under limit: ")
          .append(sales.GetSalesUnderLimit()).append("\n");

    txtOutput.setText(output.toString());

    lblYearsProcessed.setText(
        String.valueOf(sales.GetProductsProcessed())
    );
}

//saveProductData method

private void saveProductData() {

    if (txtOutput.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(
            this,
            "Please load product data first!"
        );

        return;
    }

    try {

        FileWriter writer = new FileWriter("data.txt");

        writer.write(txtOutput.getText());

        writer.close();

        JOptionPane.showMessageDialog(
            this,
            "Data saved successfully!"
        );

    } catch (IOException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage()
        );
    }
}



